import streamlit as st
import numpy as np

st.header("📐 Цифровой инспектор пространственной траектории и палеток")
st.markdown("🎯 *Комплаенс ИНТИ S.QS.07 (п. 8.5.1.3 «Контроль параметров процессов»)*")

# =================================================================
# БЛОК 1: СТАРТОВЫЙ ФИЛЬТР ЗАКАЗЧИКА И ШАГА (Стр. 3, 11, 15 памятки)
# =================================================================
col_set1, col_set2 = st.columns(2)
with col_set1:
    client_dls = st.selectbox("Укажите Заказчика по договору (Траектория):", ["Роснефть", "Газпром нефть", "Лукойл"])
with col_set2:
    step_dls = st.radio("Интервал замера (шаг палетки):", ["Посвечно (30 м)", "Пометражно (10 м)", "Свой интервал (ввод вручную)"])

# Динамическое определение длины интервала проходки (L)
if step_dls == "Посвечно (30 м)":
    delta_l = 30.0
elif step_dls == "Пометражно (10 м)":
    delta_l = 10.0
else:
    delta_l = st.number_input("Введите фактическую длину интервала между замерами, м:", value=28.5, step=0.5)

st.markdown("---")

# =================================================================
# БЛОК 2: ВВОД ДАННЫХ ИНКЛИНОМЕТРИИ (Стр. 12, 14 памятки)
# =================================================================
st.subheader("📝 Ввод фактических замеров телеметрии (MWD):")
st.info("💡 **Инструкция СМК:** Для расчета истинной пространственной интенсивности введите параметры предыдущей и последней точек замера.")

col_pt1, col_pt2 = st.columns(2)

with col_pt1:
    st.markdown("**Точка 1 (Предыдущий замер)**")
    inc1 = st.number_input("Зенитный угол Точки 1, град:", value=15.00, step=0.01, format="%.2f", key="inc1")
    azi1 = st.number_input("Азимут дирекционный Точки 1, град:", value=90.00, step=0.01, format="%.2f", key="azi1")

with col_pt2:
    st.markdown("**Точка 2 (Последний полученный замер)**")
    inc2 = np.round(st.number_input("Зенитный угол Точки 2, град:", value=18.00, step=0.01, format="%.2f", key="inc2"), 2)
    azi2 = np.round(st.number_input("Азимут дирекционный Точки 2, град:", value=90.00, step=0.01, format="%.2f", key="azi2"), 2)

st.markdown("---")

# =================================================================
# БЛОК 3: МАТЕМАТИЧЕСКИЙ РАСЧЕТ 3D-ИСКРИВЛЕНИЯ (Формула Любинского)
# =================================================================
# Переводим градусы в радианы, чтобы тригонометрия Python считала корректно
i1_rad = np.radians(inc1)
i2_rad = np.radians(inc2)
da_rad = np.radians(azi2 - azi1)

# Базовая формула Любинского для трехмерного пространственного изгиба (ω)
cos_omega = np.cos(i1_rad) * np.cos(i2_rad) + np.sin(i1_rad) * np.sin(i2_rad) * np.cos(da_rad)
cos_omega = np.clip(cos_omega, -1.0, 1.0) # Защита от машинной погрешности округления Python
omega_rad = np.arccos(cos_omega)
omega_deg = np.degrees(omega_rad)

# Расчет пространственной интенсивности (DLS), приведенной к стандарту 10 метров проходки
dls_10m = (omega_deg / delta_l) * 10.0

st.subheader("📊 Результаты расчета пространственной интенсивности:")
col_res1, col_res2 = st.columns(2)
with col_res1:
    st.metric(label="Пространственный угол изгиба ствола (ω):", value=f"{omega_deg:.3f}°")
with col_res2:
    st.metric(label="Интенсивность искривления (DLS) один в один с Бурсофт:", value=f"{dls_10m:.2f}° / 10 м")

# =================================================================
# БЛОК 4: КОРПОРАТИВНЫЙ КОМПЛАЕНС И ПРЕДУПРЕЖДЕНИЯ (Оптимизированный)
# =================================================================
limits_dls = {"Роснефть": 1.5, "Газпром нефть": 1.8, "Лукойл": 2.0}
allowed_limit = limits_dls[client_dls]

if dls_10m > allowed_limit:
    # Вместо st.error + st.warning собираем все в один безопасный st.markdown-блок
    st.markdown(f"""
    <div style="background-color: #ffcccc; padding: 15px; border-radius: 5px; border-left: 6px solid #ff0000; margin-bottom: 10px;">
        <h4 style="color: #cc0000; margin: 0;">🟥 КРИТИЧЕСКОЕ ПРЕВЫШЕНИЕ ПРОСТРАНСТВЕННОЙ ИНТЕНСИВНОСТИ ЗАКАЗЧИКА {client_dls.upper()}!</h4>
        <p style="color: #333333; margin-top: 5px; font-weight: bold;">Лимит договора: {allowed_limit}°/10м | Фактически получено: {dls_10m:.2f}°/10м</p>
    </div>
    """, unsafe_allow_html=True)
    
    st.warning(f"""
    **🚨 ТЕХНОЛОГИЧЕСКИЙ СТАТУС НАРУШЕНИЯ (Регламент Р-ТС-12):**
    * Ствол скважины уходит в скрытый жесткий перелом ('Собачья нога' по Стр. 6)!
    * **Прямое требование СМК (Стр. 7 памятки):** Немедленно сделать прогноз на забой и на дальнейшее бурение до точек Т1 и Т3 в ПО 'Бурсофт'! 
    * Если фактическая интенсивность не соответствует расчетной — увеличить длину слайда. При бурении в песках/солях — снизить расход ПЖ и увеличить нагрузку на долото.
    """)
    
    if client_dls == "Роснефть":
        st.info("⏱️ **РЕГЛАМЕНТ РОСНЕФТИ (Стр. 2):** Объявить Стоп-Приказ. Немедленно связаться с координатором проекта для корректировки План-программы.")
else:
    st.success(f"🟩 **КОНТРОЛЬ СМК ПРОЙДЕН:** Интенсивность {dls_10m:.2f}°/10м находится в границах допуска Заказчика {client_dls} (Лимит: {allowed_limit}°/10м).")

st.markdown("---")

# =================================================================
# ОБНОВЛЕННЫЙ БЛОК 5: ПРЕДИКТИВНЫЙ РАСЧЕТ С УЧЕТОМ ЛИТОЛОГИИ СВИТ
# =================================================================
st.subheader("🔮 Предиктивная аналитика СМК: Прогноз с учетом литологии свит")
st.write("Программа корректирует длину слайда на основе естественной анизотропии и размываемости пластов.")

col_geo1, col_geo2 = st.columns(2)
with col_geo1:
    # Инженер выбирает свиту, в которой сейчас находится забой (Стр. 25 методички)
    svita = st.selectbox(
        "Выберите текущую геологическую свиту/пласт:",
        ["Покурская свита (Пески / Каверны)", "Ганькинская свита (Пластичные глины)", "Алымская свита (Неустойчивый интервал)", "Аргиллиты / Плотные породы"]
    )
with col_geo2:
    target_i = st.number_input("Какую интенсивность (изменение профиля) НЕОБХОДИМО получить далее, град:", value=1.2, step=0.1, format="%.1f", key="target_i_geo")

# Ввод метража текущего слайда для калибровки инструмента
kms = st.number_input("Сколько метров СЛАЙДА фактически пробурено на текущем интервале для калибровки, м:", value=4.0, step=0.1, format="%.1f", key="kms_geo")

# Матрица поправочных коэффициентов СМК
geo_coefficients = {
    "Покурская свита (Пески / Каверны)": 0.75,
    "Ганькинская свита (Пластичные глины)": 1.10,
    "Алымская свита (Неустойчивый интервал)": 1.00,
    "Аргиллиты / Плотные породы": 1.00
}
k_lit = geo_coefficients[svita]

if kms > 0:
    i1_pure = dls_10m / 10.0  # Чистая геометрическая интенсивность за 1 метр (Стр. 11)
    i1_predicted = i1_pure * k_lit  # Научная новизна: Интенсивность с учетом литологии пласта!
    
    if i1_predicted > 0:
        needed_l = target_i / i1_predicted  # Скорректированная длина слайда
        
        st.markdown(f"📊 **Метрологический профиль пласта:** Базовая интенсивность КНБК: `{i1_pure:.4f}°/м`. Коэффициент пласта \(K_{{лит}}\) для **{svita}** составляет **{k_lit}**.")
        st.info(f"📈 **Скорректированная проактивная интенсивность:** инструмент в данном пласте будет набирать угол со скоростью **{i1_predicted:.4f}° на 1 метр**.")
        
        if needed_l > delta_l:
            st.error(f"⚠️ **ТЕХНИЧЕСКИЙ ТУПИК:** С учетом свойств пласта потребная длина слайда ({needed_l:.2f} м) превышает длину свечи ({delta_l} м). Инструмент не успеет набрать угол! Требуется изменить Toolface.")
        else:
            st.success(f"🛠️ **СКОРРЕКТИРОВАННАЯ РЕКОМЕНДАЦИЯ СМК:** Чтобы точно выйти в план с учетом геологии, на следующей свече бурите в слайде **{needed_l:.2f} метров**.")
            
        # Специфические выгрузки предупреждений из ваших ДНА по свитам (Страница 6, 25 методички)
        if svita == "Покурская свита (Пески / Каверны)":
            st.warning("🟨 **ИНСТРУКЦИЯ СМК ПО ПЕСКАМ (Стр. 6):** Фактическая интенсивность в песках падает из-за размыва ствола. Рекомендуется снизить расход промывочной жидкости (ПЖ) и увеличить осевую нагрузку на долото для удержания траектории!")
        elif svita == "Ганькинская свита (Пластичные глины)":
            st.info("ℹ️ **ПРЕДУПРЕЖДЕНИЕ ПО ГЛИНАМ:** Глины склонны к повышенному набору угла. Контролируйте слайд пометражно, чтобы избежать образования микроуступов ('собачьих ног').")
        elif svita == "Алымская свита (Неустойчивый интервал)":
            st.error("🟥 **ВНИМАНИЕ! ЗАПРЕТ ПО АЛЫМСКОЙ СВИТЕ (Стр. 25):** За 50 м до вскрытия свиты должна быть проведена финальная промывка (1.5 цикла, 36 л/с, 80 об/мин) с расхаживанием. В САМОЙ АЛЫМСКОЙ СВИТЕ ЛЮБЫЕ ПРОМЫВКИ КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНЫ во избежание обрушения стенок!")

# Подвал с авторством для диссертации ВАК
st.markdown("---")
